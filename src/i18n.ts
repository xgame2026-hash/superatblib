const locale = ref<Locale>("zh");
export const currentLocale = locale;

export function normalizeLocale(value?: string): Locale {
  const normalized = (value || "").trim().toLowerCase();
  return locales.includes(normalized as Locale) ? (normalized as Locale) : "zh";
}

export function setLocale(value: string): Locale {
  locale.value = normalizeLocale(value);
  document.documentElement.lang = locale.value === "zh" ? "zh-CN" : locale.value;
  return locale.value;
}

export function getLocale(): Locale {
  return locale.value;
}

export function t(key: string, params: Params = {}): string {
  const template = dictionaries[locale.value][key] ?? dictionaries.en[key] ?? dictionaries.zh[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export function displayStatus(value?: string): string {
  const status = String(value || "").trim();
  if (!status || status === "--") return status || "--";
  if (status === "RPC已接入" || status === "RPC 已接入") return t("status.rpcConnected");
  if (status === "候选运行中") return t("dashboard.candidateRunning");
  if (/可执行/.test(status)) return t("snapshot.executable");
  if (/就绪|ready/i.test(status)) return t("status.ready");
  if (/待部署/.test(status)) return t("status.deploying");
  if (/未连接|offline/i.test(status)) return t("status.offline");
  if (/待命|standby/i.test(status)) return t("status.standby");
  if (/排队|候选/.test(status)) return t("snapshot.candidate");
  if (/运行/.test(status)) return t("liquidation.running");
  return status;
}
